import assert from 'node:assert/strict';
import {solarAltitude,skyDate,bestSkyWindow,auroraState,clothing,SKY_POINTS} from '../public/weather-logic.js';
import {fetchSkyData} from '../worker/weather.mjs';
const time=s=>Date.parse(s)/1000;
assert(solarAltitude(time('2027-03-20T12:00:00Z'),0,0)>85);
assert(solarAltitude(time('2027-03-20T00:00:00Z'),0,0)<-85);
assert.equal(skyDate(time('2027-01-01T23:30:00Z')),'2027-01-02');
const now=time('2027-01-01T20:00:00Z');const p={...SKY_POINTS[0],current:{time:now,cloud_cover:20,precipitation:0},hourly:{time:[now+3600,now+7200,now+86400],cloud_cover:[80,20,0],precipitation:[0,0,0],wind_speed_10m:[4,4,4],apparent_temperature:[-10,-11,-12]}};
assert.equal(bestSkyWindow(p,now).time,now+7200);
const a={observationTime:new Date(now*1000).toISOString(),forecastTime:new Date((now+1800)*1000).toISOString(),values:{tromso:40}};
assert(auroraState(p,a,now).includes('可留意'));
assert(auroraState(p,a,now+10800).includes('过期'));
assert(auroraState({...p,current:{...p.current,cloud_cover:90}},a,now).includes('遮挡'));
assert(clothing(NaN).includes('暂无'));assert(clothing(-15,10,1,true).includes('防水'));
const fakeWeather=SKY_POINTS.map(()=>({current:{time:now},daily:{time:[now]},hourly:{time:[now]}}));
const partial=await fetchSkyData(async url=>{if(String(url).includes('noaa.gov'))throw Error('offline');return new Response(JSON.stringify(fakeWeather))},now*1000);
assert.equal(partial.points.length,8);assert.equal(partial.aurora,null);assert.equal(partial.errors.length,1);
const offline=await fetchSkyData(async()=>{throw Error('offline')},now*1000);assert.equal(offline.points.length,0);assert.equal(offline.errors.length,2);
console.log('PASS Oslo dates, dark-sky window, stale-data suppression, partial upstream failure and clothing advice');
